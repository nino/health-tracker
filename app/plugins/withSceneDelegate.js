// Adopts the UIScene life cycle on iOS. Apps linked against the iOS 27 SDK
// that don't adopt it crash at launch (EXC_BREAKPOINT in UIKit's
// `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`), and the
// SDK 57 prebuild template still creates its window in the AppDelegate.
//
// expo 57.0.30 ships `ExpoAppSceneDelegate`, which creates the window from the
// scene, starts React Native into it, and forwards scene URL / user-activity /
// life-cycle events back to the AppDelegate (deduping the RCTLinkingManager
// calls SDK 57's AppDelegate already makes, so deep links fire once). This
// plugin wires it up the way the SDK 58 template does: an Info.plist scene
// manifest, a `SceneDelegate` subclass, and an AppDelegate that only builds the
// React Native factory. Drop it once we're on an SDK whose template does this.
const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const SCENE_DELEGATE = `internal import Expo

@objc(SceneDelegate)
class SceneDelegate: ExpoAppSceneDelegate {
  // Generated by plugins/withSceneDelegate.js.
}
`;

const WINDOW_SETUP =
  /\n#if os\(iOS\) \|\| os\(tvOS\)\n {4}window = UIWindow\(frame: UIScreen\.main\.bounds\)\n {4}factory\.startReactNative\(\n[^#]*\n#endif\n/;

function replaceOrThrow(src, pattern, replacement, what) {
  if (!src.match(pattern)) {
    throw new Error(
      `withSceneDelegate: couldn't find ${what} in AppDelegate.swift; the Expo template changed, update the plugin.`,
    );
  }
  return src.replace(pattern, replacement);
}

function withSceneDelegate(config) {
  config = withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    };
    return config;
  });

  config = withAppDelegate(config, (config) => {
    if (config.modResults.language !== "swift") {
      throw new Error("withSceneDelegate: expected a Swift AppDelegate.");
    }
    let src = config.modResults.contents;
    if (
      !/class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider \{/.test(
        src,
      )
    ) {
      src = replaceOrThrow(
        src,
        /class AppDelegate: ExpoAppDelegate \{/,
        "class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {",
        "the AppDelegate class declaration",
      );
    }
    if (src.includes("UIWindow(")) {
      // SceneDelegate must be the only place React Native starts.
      src = replaceOrThrow(
        src,
        WINDOW_SETUP,
        "\n    // SceneDelegate creates the window and starts React Native (UIScene life cycle).\n",
        "the UIWindow setup block",
      );
    }
    config.modResults.contents = src;
    return config;
  });

  config = withXcodeProject(config, (config) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(
      config.modRequest.projectRoot,
    );
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!config.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: config.modResults,
      });
    }
    return config;
  });

  return withDangerousMod(config, [
    "ios",
    async (config) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(
        config.modRequest.projectRoot,
      );
      fs.writeFileSync(
        path.join(
          config.modRequest.platformProjectRoot,
          projectName,
          "SceneDelegate.swift",
        ),
        SCENE_DELEGATE,
      );
      return config;
    },
  ]);
}

module.exports = withSceneDelegate;
